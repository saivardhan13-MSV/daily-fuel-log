import json
from pathlib import Path

import pytest

from app.domain.targets import TargetInputs, calculate_bmr, calculate_targets, js_round


def test_js_round_is_half_up_not_bankers():
    # Python's round(2.5) == 2 and round(0.5) == 0; Math.round gives 3 and 1.
    assert js_round(2.5) == 3
    assert js_round(0.5) == 1
    assert js_round(1.5) == 2
    assert js_round(2.4) == 2


def test_bmr_male_and_female():
    male = TargetInputs(78, 178, 30, "male", "moderate", "maintain")
    female = TargetInputs(78, 178, 30, "female", "moderate", "maintain")
    assert calculate_bmr(male) == 10 * 78 + 6.25 * 178 - 5 * 30 + 5
    assert calculate_bmr(female) == 10 * 78 + 6.25 * 178 - 5 * 30 - 161


def test_known_target_fixture():
    # 78kg / 178cm / 30y male, moderate, maintain:
    # BMR 1747.5 -> TDEE 2708.625 -> 2709 kcal; protein 1.8 * 78 = 140.4 -> 140
    t = calculate_targets(TargetInputs(78, 178, 30, "male", "moderate", "maintain"))
    assert t.calories == 2709
    assert t.protein == 140
    assert t.fat == 75  # 25% of 2709 kcal = 677.25 / 9 = 75.25
    assert t.carbs == 368  # (2709 - 560 - 677.25) / 4 = 367.9


def test_matches_typescript_implementation_on_810_golden_cases():
    """Golden file generated by running the original TypeScript calculateTargets
    (since removed from the app; see git history) over a grid of inputs. Guards the port against rounding drift (Math.round is
    half-up; Python's round() is banker's rounding)."""
    path = Path(__file__).parent / "fixtures" / "ts_target_parity.json"
    cases = json.loads(path.read_text())
    assert len(cases) == 810
    for c in cases:
        got = calculate_targets(
            TargetInputs(c["weight_kg"], c["height_cm"], c["age"], c["sex"], c["activity_level"], c["goal"])
        )
        assert (got.calories, got.protein, got.carbs, got.fat) == (
            c["calories"], c["protein"], c["carbs"], c["fat"]
        ), c


def test_goal_shifts_calories_and_protein():
    base = TargetInputs(80, 180, 28, "male", "active", "maintain")
    cut = calculate_targets(TargetInputs(**{**base.__dict__, "goal": "cut"}))
    bulk = calculate_targets(TargetInputs(**{**base.__dict__, "goal": "bulk"}))
    maintain = calculate_targets(base)
    assert cut.calories < maintain.calories < bulk.calories
    assert cut.protein > maintain.protein > bulk.protein


def test_carbs_never_negative():
    # A heavy protein load on a tiny calorie budget must clamp to 0, not go negative.
    t = calculate_targets(TargetInputs(200, 150, 80, "female", "sedentary", "cut"))
    assert t.carbs >= 0


@pytest.mark.parametrize("level", ["sedentary", "light", "moderate", "active", "very_active"])
def test_every_activity_level_supported(level):
    assert calculate_targets(TargetInputs(70, 170, 25, "female", level, "maintain")).calories > 0
